"""Generate m68kemu_shadow_layouts.h from the m68k offsets file."""
#
# Usage: gen_shadow_layouts.py m68k_offsets.txt > m68kemu_shadow_layouts.h
# Input lines:  OFF|Struct|field|m68k offset|m68k size|native member|
#               SIZ|Struct|m68k size|native header|
#
# Only the m68k side is written as numbers. The native side is left to the
# compiler of the target: the offset of a field is offsetof() on its member,
# and a 4-byte field is a pointer where the native member has 8 bytes.
# A field without a member has no native counterpart and gets no entry.
import sys

MACROS = """/*
 * The native side of a field. A structure that embeds a spinlock_t, such as
 * Library, Task or MsgPort, has another layout on every target, so the offset
 * is offsetof() on the member. A 4-byte m68k field is a pointer where the
 * native member has 8 bytes, and a LONG otherwise.
 */
#define SHADOW_FIELD_TYPE(m68k_size, native_size) \\
    ((m68k_size) == 1 ? SF_BYTE : (m68k_size) == 2 ? SF_WORD : \\
     (native_size) == 8 ? SF_PTR : SF_LONG)
#define SHADOW_FIELD(m68k_off, m68k_size, name, member) \\
    { m68k_off, offsetof(struct name, member), \\
      SHADOW_FIELD_TYPE(m68k_size, sizeof(((struct name *)0)->member)), \\
      0, 0, NULL }
"""

def parse(path):
    structs = {}
    sizes = {}
    headers = {}
    for line in open(path):
        line = line.strip().rstrip('|')
        parts = line.split('|')
        if parts[0] == 'OFF' and len(parts) == 6:
            _, sname, _, off, sz, member = parts
            structs.setdefault(sname, []).append((member, int(off), int(sz)))
        elif parts[0] == 'SIZ':
            sizes[parts[1]] = int(parts[2])
            if len(parts) == 4:
                headers[parts[1]] = parts[3]
    return structs, sizes, headers

def main():
    if len(sys.argv) != 2:
        print(f"Usage: {sys.argv[0]} m68k_offsets.txt", file=sys.stderr)
        sys.exit(1)
    sys.stdout.reconfigure(encoding="utf-8")

    m68k_structs, m68k_sizes, headers = parse(sys.argv[1])

    layouts = []
    for sname in sorted(m68k_structs.keys()):
        # the engine maps fields of 1, 2 and 4 bytes
        entries = [e for e in m68k_structs[sname] if e[2] in (1, 2, 4)]
        if not entries:
            continue
        if sname not in headers:
            sys.exit(f"{sys.argv[1]}: {sname} has members but no native header")
        layouts.append((sname, entries))

    print("/*")
    print(" * Copyright (C) 2026, The AROS Development Team. All rights reserved.")
    print(" * Author: Fabian Schmieder (@metaneutrons)")
    print(" *")
    print(" * AUTO-GENERATED by gen_shadow_layouts.py — do not edit */")
    print("#ifndef M68KEMU_SHADOW_LAYOUTS_H")
    print("#define M68KEMU_SHADOW_LAYOUTS_H\n")
    print("#include <stddef.h>")
    for header in sorted({headers[sname] for sname, _ in layouts}):
        print(f"#include <{header}>")
    print()
    print(MACROS)

    emitted = []
    shadow_type = 20  # start numbering after manual types (0-19 reserved)

    for sname, entries in layouts:
        print(f"/* {sname}: m68k={m68k_sizes.get(sname,'?')}B, "
              f"{len(entries)} fields */")
        print(f"static const struct M68KFieldMap shadow_fields_{sname}[] = {{")
        for member, m_off, m_sz in entries:
            print(f"    SHADOW_FIELD({m_off:4d}, {m_sz}, {sname}, {member}),")
        print("    {    0,    0, SF_END  , 0, 0, NULL }")
        print("};\n")

        emitted.append((sname, shadow_type, m68k_sizes.get(sname, 0)))
        shadow_type += 1

    # Lookup table
    print("/* Lookup table: find layout by struct name */")
    print("static const struct M68KStructLayout shadow_gen_layouts[] = {")
    for sname, stype, m68k_sz in emitted:
        print(f"    {{ \"{sname}\", {m68k_sz}, {stype}, shadow_fields_{sname} }},")
    print("    { NULL, 0, 0, NULL }")
    print("};\n")
    print(f"#define SHADOW_GEN_LAYOUT_COUNT {len(emitted)}")

    print("\n#endif /* M68KEMU_SHADOW_LAYOUTS_H */")

if __name__ == '__main__':
    main()
