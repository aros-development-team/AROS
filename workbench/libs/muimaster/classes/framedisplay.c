/****** Framedisplay.mui/MUIC_Framedisplay ************
*
*   NAME
*       MUIC_Framedisplay
*
*   SUPERCLASS
*       Area.mui
*
*   DESCRIPTION
*       Preview an AROS frame specification. The class stores parsed frame
*       fields and an embedded serialization buffer; it does not retain the
*       input pointer. With no Spec tag, zero-initialized fields serialize as
*       000000. Construction returns NULL only on superclass failure; parser
*       failure is not propagated.
*
*   METHODS
*       Spec Set parses into existing state, requests full redraw for every Spec
*       tag and returns the superclass setter result. Get serializes current
*       fields into the embedded buffer and reports TRUE. Size negotiation adds
*       eight to both minima and sixteen to both defaults, sets maxima
*       MUI_MAXMAX and returns one, independent of chosen frame.
*       Draw calls Area and requires MADF_DRAWOBJECT. It resolves the frame
*       renderer, draws across outer bounds and draws shadow-pen diagonal lines
*       inside the frame/margin region under clipping. It returns zero on flag
*       rejection or unavailable renderer, otherwise one. Clipping failure is
*       not separately checked.
*       DragQuery refuses self and accepts a successful Framedisplay_Spec getter
*       without validating its data. DragDrop fetches and sets Spec without
*       checking getter status or repeating the self check, then returns zero.
*
*   NOTES
*       A specification is a NUL-terminated string of six to eight characters:
*       frame type, state, left, right, top, bottom margins, optional radius and
*       optional width. Type uses digits then letters and must be below
*       FST_COUNT; state is zero or one. Margins and optional fields are
*       hexadecimal 0..f. The parser also accepts uppercase letters. Omitted
*       optional fields become zero after the first six fields parse.
*       Parsing is not transactional: invalid later characters can leave earlier
*       fields changed. NULL or invalid length returns before field updates.
*       This class ignores that status, so use valid input. Serialization uses
*       six characters when both optional values are zero, otherwise eight. Get
*       returns borrowed mutable storage valid until disposal and overwritten by
*       another Get; the resulting string may be passed to Set.
*
*/
/****** Framedisplay.mui/MUIA_Framedisplay_Spec ************
*
*   NAME
*       MUIA_Framedisplay_Spec
*
*   FUNCTION
*       Parse or retrieve the preview frame specification.
*
*   INPUTS
*       Initialize, set and get. Supply a valid NUL-terminated
*       frame-specification string; Get returns STRPTR to embedded storage
*       despite the header structure-pointer annotation.
*
*   NOTES
*       Input is parsed synchronously, not retained or copied as a complete
*       structure. The class contract defines field order and validation limits.
*       Parser failure is ignored and can partially update fields. Set requests
*       full redraw, not relayout. Get normalizes to six or eight characters and
*       reports success; its borrowed pointer lasts until disposal but its
*       contents are regenerated by Get.
*
*/

extern struct Library *MUIMasterBase;

/*
 * Construct Area and parse Spec tags into embedded fields, ignoring parser
 * failure; return object or zero on superclass failure. Requires readable
 * terminated input when non-NULL. No pointer ownership transfer; defaults
 * are zeroed fields.
 */
IPTR Framedisplay__OM_NEW(struct IClass *cl, Object *obj, struct opSet *msg)
{
    struct Framedisplay_DATA *data;
    struct TagItem *tags;
    struct TagItem *tag;

    D(bug("Framedisplay_New starts\n"));

    obj = (Object *)DoSuperMethodA(cl, obj, (Msg)msg);
    if (!obj)
        return FALSE;

    data = INST_DATA(cl, obj);

    /* parse initial taglist */

    for (tags = msg->ops_AttrList; (tag = NextTagItem(&tags));) {
        switch (tag->ti_Tag) {
        case MUIA_Framedisplay_Spec:
            zune_frame_spec_to_intern((CONST_STRPTR)tag->ti_Data, &data->fs_intern);
            break;
        }
    }

    D(bug("Framedisplay_New(%lx) spec=%lx\n", obj, data->fs_intern));
    return (IPTR)obj;
}

/*
 * Parse every Spec into existing fields and request full redraw, then
 * return Area setter result. Parser failure can leave partial updates; no
 * relayout or error propagation. Input is consumed synchronously.
 */
IPTR Framedisplay__OM_SET(struct IClass *cl, Object *obj, struct opSet *msg)
{
    struct Framedisplay_DATA *data = INST_DATA(cl, obj);
    struct TagItem *tags;
    struct TagItem *tag;

    for (tags = msg->ops_AttrList; (tag = NextTagItem(&tags));) {
        switch (tag->ti_Tag) {
        case MUIA_Framedisplay_Spec:
            zune_frame_spec_to_intern((CONST_STRPTR)tag->ti_Data, &data->fs_intern);
            MUI_Redraw(obj, MADF_DRAWOBJECT);
            break;
        }
    }

    return (IPTR)DoSuperMethodA(cl, obj, (Msg)msg);
}

/*
 * Serialize embedded frame to instance buffer and store its borrowed
 * pointer with TRUE; delegate other queries. Requires writable IPTR
 * storage. Buffer lasts until disposal and is overwritten by Get; no
 * allocation.
 */
IPTR Framedisplay__OM_GET(struct IClass *cl, Object *obj, struct opGet *msg)
{
    struct Framedisplay_DATA *data = INST_DATA(cl, obj);
    switch (msg->opg_AttrID) {
    case MUIA_Framedisplay_Spec:
        zune_frame_intern_to_spec(&data->fs_intern, (STRPTR)data->spec);
        *msg->opg_Storage = (IPTR)data->spec;
        return (TRUE);
    }

    return (IPTR)DoSuperMethodA(cl, obj, (Msg)msg);
}

/*
 * Call Area, add minima eight/defaults sixteen on both axes, assign
 * unlimited maxima and return one. Requires writable MinMaxInfo.
 * Contributions are independent of selected frame and margins.
 */
IPTR Framedisplay__MUIM_AskMinMax(struct IClass *cl, Object *obj,
                                  struct MUIP_AskMinMax *msg)
{
    DoSuperMethodA(cl, obj, (Msg)msg);

    msg->MinMaxInfo->MinWidth += 8;
    msg->MinMaxInfo->MinHeight += 8;

    msg->MinMaxInfo->DefWidth += 16;
    msg->MinMaxInfo->DefHeight += 16;

    msg->MinMaxInfo->MaxWidth = MUI_MAXMAX;
    msg->MinMaxInfo->MaxHeight = MUI_MAXMAX;

    return 1;
}

/*
 * Call Area, require full drawing and resolved renderer, then draw outer
 * frame and clipped inner diagonal sample. Return zero if
 * rejected/unresolved, otherwise one. Requires live drawing resources;
 * clipping failure is not explicitly checked and resources remain borrowed.
 */
IPTR Framedisplay__MUIM_Draw(struct IClass *cl, Object *obj,
                             struct MUIP_Draw *msg)
{
    struct Framedisplay_DATA *data = INST_DATA(cl, obj);
    const struct ZuneFrameGfx *zframe;
    APTR region;
    WORD ileft, itop, iright, ibottom;
    int i;

    DoSuperMethodA(cl, obj, (Msg)msg);

    if (!(msg->flags & MADF_DRAWOBJECT))
        return 0;

    zframe = zune_zframe_get(obj, &data->fs_intern);
    if (!zframe)
        return 0;

    struct dt_frame_image temp_frame;
    struct MUI_FrameSpec_intern tempframe;
    struct dt_frame_image *frame_img =
        zune_frame_prepare_for_drawing(zframe, &data->fs_intern, &temp_frame);

    zframe->draw(frame_img, muiRenderInfo(obj), _left(obj), _top(obj),
                 _width(obj), _height(obj), _left(obj), _top(obj), _width(obj),
                 _height(obj));

    ileft = _mleft(obj) + zframe->ileft + data->fs_intern.innerLeft;
    itop = _mtop(obj) + zframe->itop + data->fs_intern.innerTop;
    iright = _mright(obj) - zframe->iright - data->fs_intern.innerRight;
    ibottom = _mbottom(obj) - zframe->ibottom - data->fs_intern.innerBottom;

    SetAPen(_rp(obj), _pens(obj)[MPEN_SHADOW]);

    region = MUI_AddClipping(muiRenderInfo(obj), ileft, itop, iright - ileft + 1,
                             ibottom - itop + 1);

    for (i = itop; i < ibottom + iright - ileft; i++) {
        if (!(i % 4)) {
            Move(_rp(obj), ileft, i);
            Draw(_rp(obj), ileft + i - itop, itop);
        }
    }

    MUI_RemoveClipping(muiRenderInfo(obj), region);

    return 1;
}

/*
 * Refuse self or failed Framedisplay_Spec Get, otherwise accept without
 * inspecting returned string. Requires live source object; no data copy or
 * ownership transfer.
 */
IPTR Framedisplay__MUIM_DragQuery(struct IClass *cl, Object *obj,
                                  struct MUIP_DragQuery *msg)
{
    struct MUI_FrameSpec *dummy = NULL;

    if (msg->obj == obj)
        return MUIV_DragQuery_Refuse;
    if (!get(msg->obj, MUIA_Framedisplay_Spec, &dummy))
        return MUIV_DragQuery_Refuse;
    return MUIV_DragQuery_Accept;
}

/*
 * Fetch source frame Spec and pass to setter, return zero regardless of
 * getter/setter status. Requires a live source and valid returned string
 * for useful transfer; no repeated query/self validation or ownership
 * transfer.
 */
IPTR Framedisplay__MUIM_DragDrop(struct IClass *cl, Object *obj,
                                 struct MUIP_DragDrop *msg)
{
    struct MUI_FrameSpec *spec = NULL;

    get(msg->obj, MUIA_Framedisplay_Spec, &spec);
    set(obj, MUIA_Framedisplay_Spec, (IPTR)spec);
    return 0;
}

