/* multiply by x in GF(2^8) */
static inline UBYTE aes128_xtime(UBYTE b)
{
    return (UBYTE)((b << 1) ^ ((b & 0x80) ? 0x1b : 0));
}

static inline UBYTE aes128_mul(UBYTE a, UBYTE b)
{
    UBYTE r = 0;

    while (b)
    {
        if (b & 1)
            r ^= a;
        a = aes128_xtime(a);
        b >>= 1;
    }
    return r;
}

static inline void aes128_set_key(struct aes128_key *k, const UBYTE *key)
{
    UBYTE rcon = 1;
    int i;

    for (i = 0; i < 16; i++)
        k->rk[i] = key[i];
    for (i = 16; i < (AES128_ROUNDS + 1) * 16; i += 4)
    {
        UBYTE t0 = k->rk[i - 4], t1 = k->rk[i - 3], t2 = k->rk[i - 2], t3 = k->rk[i - 1];

        if ((i & 15) == 0)
        {
            /* rotate, substitute, round constant */
            UBYTE u = t0;
            t0 = aes128_sbox[t1] ^ rcon;
            t1 = aes128_sbox[t2];
            t2 = aes128_sbox[t3];
            t3 = aes128_sbox[u];
            rcon = aes128_xtime(rcon);
        }
        k->rk[i]     = k->rk[i - 16] ^ t0;
        k->rk[i + 1] = k->rk[i - 15] ^ t1;
        k->rk[i + 2] = k->rk[i - 14] ^ t2;
        k->rk[i + 3] = k->rk[i - 13] ^ t3;
    }
}

static inline void aes128_add_round_key(UBYTE *s, const UBYTE *rk)
{
    int i;

    for (i = 0; i < 16; i++)
        s[i] ^= rk[i];
}

/* the state is column-major: s[c * 4 + r] */
static inline void aes128_encrypt(const struct aes128_key *k, const UBYTE *in, UBYTE *out)
{
    UBYTE s[16], t[16];
    int round, i, c;

    for (i = 0; i < 16; i++)
        s[i] = in[i];
    aes128_add_round_key(s, k->rk);
    for (round = 1; round <= AES128_ROUNDS; round++)
    {
        /* SubBytes + ShiftRows */
        for (c = 0; c < 4; c++)
        {
            t[c * 4]     = aes128_sbox[s[c * 4]];
            t[c * 4 + 1] = aes128_sbox[s[((c + 1) & 3) * 4 + 1]];
            t[c * 4 + 2] = aes128_sbox[s[((c + 2) & 3) * 4 + 2]];
            t[c * 4 + 3] = aes128_sbox[s[((c + 3) & 3) * 4 + 3]];
        }
        if (round < AES128_ROUNDS)
        {
            /* MixColumns */
            for (c = 0; c < 4; c++)
            {
                UBYTE a0 = t[c * 4], a1 = t[c * 4 + 1], a2 = t[c * 4 + 2], a3 = t[c * 4 + 3];

                s[c * 4]     = aes128_xtime(a0) ^ (aes128_xtime(a1) ^ a1) ^ a2 ^ a3;
                s[c * 4 + 1] = a0 ^ aes128_xtime(a1) ^ (aes128_xtime(a2) ^ a2) ^ a3;
                s[c * 4 + 2] = a0 ^ a1 ^ aes128_xtime(a2) ^ (aes128_xtime(a3) ^ a3);
                s[c * 4 + 3] = (aes128_xtime(a0) ^ a0) ^ a1 ^ a2 ^ aes128_xtime(a3);
            }
        }
        else
        {
            for (i = 0; i < 16; i++)
                s[i] = t[i];
        }
        aes128_add_round_key(s, k->rk + round * 16);
    }
    for (i = 0; i < 16; i++)
        out[i] = s[i];
}

static inline void aes128_decrypt(const struct aes128_key *k, const UBYTE *in, UBYTE *out)
{
    UBYTE s[16], t[16];
    int round, i, c;

    for (i = 0; i < 16; i++)
        s[i] = in[i];
    aes128_add_round_key(s, k->rk + AES128_ROUNDS * 16);
    for (round = AES128_ROUNDS - 1; round >= 0; round--)
    {
        /* InvShiftRows + InvSubBytes */
        for (c = 0; c < 4; c++)
        {
            t[c * 4]     = aes128_inv_sbox[s[c * 4]];
            t[c * 4 + 1] = aes128_inv_sbox[s[((c + 3) & 3) * 4 + 1]];
            t[c * 4 + 2] = aes128_inv_sbox[s[((c + 2) & 3) * 4 + 2]];
            t[c * 4 + 3] = aes128_inv_sbox[s[((c + 1) & 3) * 4 + 3]];
        }
        aes128_add_round_key(t, k->rk + round * 16);
        if (round > 0)
        {
            /* InvMixColumns */
            for (c = 0; c < 4; c++)
            {
                UBYTE a0 = t[c * 4], a1 = t[c * 4 + 1], a2 = t[c * 4 + 2], a3 = t[c * 4 + 3];

                s[c * 4]     = aes128_mul(a0, 14) ^ aes128_mul(a1, 11) ^ aes128_mul(a2, 13) ^ aes128_mul(a3, 9);
                s[c * 4 + 1] = aes128_mul(a0, 9)  ^ aes128_mul(a1, 14) ^ aes128_mul(a2, 11) ^ aes128_mul(a3, 13);
                s[c * 4 + 2] = aes128_mul(a0, 13) ^ aes128_mul(a1, 9)  ^ aes128_mul(a2, 14) ^ aes128_mul(a3, 11);
                s[c * 4 + 3] = aes128_mul(a0, 11) ^ aes128_mul(a1, 13) ^ aes128_mul(a2, 9)  ^ aes128_mul(a3, 14);
            }
        }
        else
        {
            for (i = 0; i < 16; i++)
                s[i] = t[i];
        }
    }
    for (i = 0; i < 16; i++)
        out[i] = s[i];
}

