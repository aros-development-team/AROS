#!/bin/sh
# abicheck.sh - check that the Rust libc crate's AROS types match the C headers.
#
#   abicheck.sh LIST OUTDIR CC RUSTC NM [LIBC-SOURCE-DIR...]
#
# LIST     abi-types.txt: "<rust type> | <C type> | <headers> [| opaque|rust]"
# OUTDIR   scratch directory (created); the report is OUTDIR/abicheck.txt
# CC       target C compiler command (sysroot and ABI flags included)
# RUSTC    target rustc command (--target included)
# NM       target nm
# LIBC-SOURCE-DIR
#          unpacked libc crate sources (AROS patch applied) to check as well,
#          e.g. the crate stores' copies. The libc inside the installed std is
#          always checked (through rustc_private).
#
# Sizes and alignments are read from symbol sizes: the C side defines
# char abi_size_<t>[sizeof(T)] and char abi_align_<t>[_Alignof(T)], the Rust
# side [u8; size_of::<libc::T>()] statics with the same names, and nm -S
# reports both. Nothing runs on the target.
#
# A type must have the same size and alignment on both sides; an "opaque"
# one only needs Rust's to be at least C's; a "rust" one is listed only.
# A type the libc copy does not define is reported as MISSING. Exits 1 when
# anything differs or is missing.

set -u
LIST=$1; OUT=$2; CC=$3; RUSTC=$4; NM=$5; shift 5

mkdir -p "$OUT" || exit 1
REPORT=$OUT/abicheck.txt
: > "$REPORT"
types=$OUT/types.lst
grep -v '^[[:space:]]*#' "$LIST" | grep '|' \
    | sed 's/[[:space:]]*|[[:space:]]*/|/g; s/^[[:space:]]*//; s/[[:space:]]*$//' > "$types"
ntypes=$(wc -l < "$types")

sizes() {           # symbol sizes of an object: "<symbol> <decimal size>"
    $NM -S "$1" | awk '$4 ~ /^abi_(size|align)_/ { print $4, strtonum("0x" $2) }' | sort
}

# ---- C side ------------------------------------------------------------------
cfile=$OUT/abi_c.c
{
    echo '/* generated by abicheck.sh */'
    cut -d'|' -f3 "$types" | tr ' ' '\n' | grep . | sort -u | sed 's/.*/#include <&>/'
    while IFS='|' read -r rt ct hdr kind; do
        echo "char abi_size_$rt[sizeof($ct)];"
        echo "char abi_align_$rt[_Alignof($ct)];"
    done < "$types"
} > "$cfile"
if ! $CC -fno-common -c -o "$OUT/abi_c.o" "$cfile" > "$OUT/abi_c.log" 2>&1; then
    echo "abicheck: the C side does not compile (a header or type in $LIST is wrong):" >&2
    cat "$OUT/abi_c.log" >&2
    exit 1
fi
sizes "$OUT/abi_c.o" > "$OUT/c.sizes"

# ---- Rust side ---------------------------------------------------------------
rust_source() {     # $1: 1 = the libc inside std (rustc_private); $2: types to leave out
    echo '// generated by abicheck.sh'
    if [ "$1" = 1 ]; then
        echo '#![feature(rustc_private)]'
        echo '#![allow(non_upper_case_globals)]'
        echo 'extern crate libc;'
    else
        echo '#![allow(non_upper_case_globals)]'
    fi
    echo 'use core::mem::{align_of, size_of};'
    while IFS='|' read -r rt ct hdr kind; do
        case " $2 " in *" $rt "*) continue ;; esac
        echo "#[no_mangle] #[used] pub static abi_size_$rt: [u8; size_of::<libc::$rt>()] = [0; size_of::<libc::$rt>()];"
        echo "#[no_mangle] #[used] pub static abi_align_$rt: [u8; align_of::<libc::$rt>()] = [0; align_of::<libc::$rt>()];"
    done < "$types"
}

# rust_object LABEL STD OBJ [rustc args]: compile the Rust side; types the
# libc copy does not have are dropped and remembered in OBJ.missing.
rust_object() {
    label=$1; std=$2; obj=$3; shift 3
    missing=""
    for try in 1 2 3; do
        rust_source "$std" "$missing" > "$obj.rs"
        if RUSTC_BOOTSTRAP=1 $RUSTC --edition 2021 --crate-name abicheck --crate-type lib --emit obj -O "$@" \
                -o "$obj" "$obj.rs" > "$obj.log" 2>&1; then
            echo "$missing" | tr ' ' '\n' | grep . > "$obj.missing"
            return 0
        fi
        more=$(sed -n 's/.*cannot find type `\([A-Za-z0-9_]*\)` in crate `libc`.*/\1/p' "$obj.log" | sort -u | tr '\n' ' ')
        [ -z "$more" ] && break
        missing="$missing $more"
    done
    echo "abicheck: $label: the check does not compile:" >&2
    cat "$obj.log" >&2
    return 1
}

failed=0
compare() {         # LABEL OBJ
    sizes "$2" > "$2.sizes"
    bad=$(join -a1 -e MISSING -o 0,1.2,2.2 "$OUT/c.sizes" "$2.sizes" | awk -v types="$types" -v miss="$2.missing" '
        BEGIN {
            FS = " "
            while ((getline l < types) > 0) { split(l, f, "|"); kind[f[1]] = f[4] }
            while ((getline l < miss) > 0) if (l != "") gone[l] = 1
        }
        {
            t = $1; sub(/^abi_(size|align)_/, "", t)
            if (t in gone) { if ($1 ~ /^abi_size_/) print t, "MISSING from libc"; next }
            if (kind[t] == "rust") next
            if ($3 == "MISSING") { print t, $1, "C", $2, "Rust missing"; next }
            if (kind[t] == "opaque" ? ($3 + 0 < $2 + 0) : ($3 != $2))
                print t, ($1 ~ /^abi_size_/ ? "size" : "align"), "C", $2, "Rust", $3 (kind[t] == "opaque" ? " (opaque: Rust must be >= C)" : "")
        }')
    {
        echo "== $1"
        if [ -z "$bad" ]; then
            echo "all $ntypes types match"
        else
            echo "$bad"
        fi
        grep '|rust$' "$types" | cut -d'|' -f1 | sed 's/$/: Rust-side layout, not compared/'
    } >> "$REPORT"
    if [ -n "$bad" ]; then
        failed=1
        echo "abicheck: $1: libc types differ from the AROS C headers:" >&2
        echo "$bad" | sed 's/^/    /' >&2
    fi
}

# the libc inside the installed std
if rust_object "std's libc" 1 "$OUT/abi_std.o"; then
    compare "std's libc" "$OUT/abi_std.o"
else
    failed=1
fi

# libc crate sources (the crate stores' patched copies)
n=0
for src in "$@"; do
    n=$((n + 1))
    name=$(basename "$src")
    if ! $RUSTC --edition 2021 --crate-name libc --crate-type rlib --cap-lints allow -O \
            -o "$OUT/liblibc_$n.rlib" "$src/src/lib.rs" > "$OUT/libc_$n.log" 2>&1; then
        echo "abicheck: $name does not build:" >&2
        cat "$OUT/libc_$n.log" >&2
        failed=1
        continue
    fi
    if rust_object "$name" 0 "$OUT/abi_$n.o" --extern libc="$OUT/liblibc_$n.rlib"; then
        compare "$name" "$OUT/abi_$n.o"
    else
        failed=1
    fi
done

[ $failed = 0 ] && echo "abicheck: all libc types match the AROS C headers ($ntypes types)"
exit $failed
